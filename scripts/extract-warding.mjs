// ── Bows ─────────────────────────────────────────────────────────────────────
// Extract each keyway's bow (head) from its key outline. keygen positions the
// key by a shoulder-datum offset (indices below, taken from the *.scad drivers);
// we apply it, re-derive the blade back geometrically, orient so the blade is at
// +x, and lift out the bow-side loop run (bow at −x, blade back at h=0).
function parsePaths(text, name) {
  const m = text.match(new RegExp(name + '\\s*=\\s*(\\[[\\s\\S]*?\\])\\s*;'));
  return m ? [...m[1].matchAll(/\[([\d,\s]+)\]/g)].map(g => g[1].split(',').map(n => parseInt(n, 10))) : null;
}
const BOW_CFG = {  // gen file, outline var, shoulder-datum indices [x-from, y-from]
  schlage: { gen: 'schlage.gen.scad', var: 'outline_5pin_points', ox: 92, oy: 98 },
  kwikset: { gen: 'kwikset.gen.scad', var: 'outline_points', ox: 34, oy: 26 },
  master: { gen: 'master.gen.scad', var: 'outline_k1_points', ox: 61, oy: 40 },
  // BEST (SFIC) is drawn in a FLIPPED frame: its datum (points 42/37) sits at the
  // TIP and the key extends −x with cuts at negative locations ("tip to bow"),
  // opposite the others. So we don't flip; instead we set the blade back from the
  // tip region and re-shift x so the shoulder (where the outline widens past the
  // blade height) lands at 0 — then the same bow-run extraction applies.
  best: { gen: 'best.gen.scad', var: 'outline_points', ox: 42, oy: 37, tipDatum: true, bladeTop: 8.382 },
};
const bows = {};
for (const [id, cfg] of Object.entries(BOW_CFG)) {
  const text = fs.readFileSync(path.join(scadDir, cfg.gen), 'utf8');
  const P = parseArrays(text)[cfg.var];
  if (!P) { console.error(`WARN: bow ${id} outline not found`); continue; }
  const paths = parsePaths(text, cfg.var.replace('_points', '_paths'));
  const dx = -P[cfg.ox][0], dy = -P[cfg.oy][1];
  const Q = P.map(([x, y]) => [x + dx, y + dy]);
  const outer = (paths && paths[0]) ? paths[0].map(i => Q[i]) : Q;
  let B;
  if (cfg.tipDatum) {
    // Tip-datum frame (BEST): blade already runs +x from the tip; back = min y over
    // the blade (tip) region; shoulder = first x (tip→bow) whose top exceeds the
    // blade top; shift so shoulder→0.
    const maxX = Math.max(...outer.map(p => p[0]));
    const spine = Math.min(...outer.filter(p => p[0] > maxX - 28).map(p => p[1]));
    const S = outer.map(([x, h]) => [x, h - spine]);
    const dense = []; for (let i = 0; i < S.length; i++) { const a = S[i], b = S[(i + 1) % S.length]; const L = Math.hypot(b[0] - a[0], b[1] - a[1]), n = Math.max(1, Math.round(L / 0.5)); for (let k = 0; k < n; k++) dense.push([a[0] + (b[0] - a[0]) * k / n, a[1] + (b[1] - a[1]) * k / n]); }
    let sh = Math.min(...S.map(p => p[0]));
    for (let x = maxX; x > sh; x -= 0.5) { const near = dense.filter(p => Math.abs(p[0] - x) < 0.6); if (near.length && Math.max(...near.map(p => p[1])) > cfg.bladeTop + 1.5) { sh = x; break; } }
    B = S.map(([x, h]) => [x - sh, h]);
  } else {
    const span = (f) => { const ys = outer.filter(f).map(p => p[1]); return ys.length ? Math.max(...ys) - Math.min(...ys) : 1e9; };
    const flip = span(p => p[0] > 0) < span(p => p[0] < 0) ? 1 : -1; // blade to +x
    const X = outer.map(p => p[0] * flip);
    const spine = Math.min(...outer.filter((_, i) => X[i] > 1).map(p => p[1]));
    B = outer.map((p, i) => [X[i], p[1] - spine]);
  }
  const on = B.map(p => p[0] < -0.3);
  const runs = []; let cur = [];
  for (let i = 0; i < B.length; i++) { if (on[i]) cur.push(i); else if (cur.length) { runs.push(cur); cur = []; } }
  if (cur.length) runs.push(cur);
  if (on[0] && on[B.length - 1] && runs.length > 1) { runs[0] = runs[runs.length - 1].concat(runs[0]); runs.pop(); }
  const run = runs.sort((a, b) => b.length - a.length)[0];
  bows[id] = run.map(i => [round(B[i][0], 3), round(B[i][1], 3)]);
}
const BL = [...LICENSE_HEADER];
BL.push('// Manufacturer bow silhouettes (the head you grip), in mm, in the blade\'s');
BL.push('// (x=length, h=height) plane with the blade back at h=0 and the shoulder near');
BL.push('// x=0 (bow extends to negative x).');
BL.push('//');
BL.push('// GENERATED by scripts/extract-warding.mjs from ervanalb/keygen (CC0 1.0).');
BL.push('// Do not edit by hand — re-run `npm run warding`. Open chain (neck end left');
BL.push('// open); keyMesh bridges it into the blade. BEST (SFIC) is de-skewed from its');
BL.push('// flipped tip-datum frame (see BOW_CFG.best) so its real head is now included.');
BL.push('');
BL.push('export const BOWS = {');
for (const [id, b] of Object.entries(bows)) {
  BL.push(`  ${id}: [${b.map(([x, h]) => `[${x},${h}]`).join(', ')}],`);
}
BL.push('};');
BL.push('');
BL.push('export function getBow(id) { return BOWS[id] || null; }');
BL.push('');
fs.writeFileSync(path.join(root, 'js/keys/bows.js'), BL.join('\n'));

